using System;
using System.Collections.Generic;
using System.Linq;
using CodeBrix.WebPlatform.FrontendBuilder.Crates;
using SilverAssertions;
using Xunit;

namespace CodeBrix.WebPlatform.FrontendBuilder.Tests.Crates;

public class LockFileRulesTests
{
    private const string Registry = "registry+https://github.com/rust-lang/crates.io-index";

    private static string Lock(params (string Name, string Version, string Source)[] packages)
    {
        var text = LockFileRules.HeaderLine + "\n" + LockFileRules.SecondHeaderLine + "\nversion = 4\n";
        foreach (var (name, version, source) in packages)
        {
            text += $"\n[[package]]\nname = \"{name}\"\nversion = \"{version}\"\n" + (source == null ? string.Empty : $"source = \"{source}\"\n");
        }

        return text;
    }

    private static Dictionary<string, HashSet<string>> Vendored(params string[] crates)
    {
        var vendored = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        foreach (var crate in crates)
        {
            var parts = crate.Split(' ');
            if (!vendored.TryGetValue(parts[0], out var versions))
            {
                versions = new HashSet<string>(StringComparer.Ordinal);
                vendored[parts[0]] = versions;
            }

            versions.Add(parts[1]);
        }

        return vendored;
    }

    [Fact]
    public void the_marker_is_one_ascii_line_that_starts_with_the_stable_prefix()
    {
        //Assert
        PlatformCrates.LockFileMarker.Should().StartWith(PlatformCrates.LockFileMarkerPrefix);
        PlatformCrates.LockFileMarker.Should().StartWith("# ");
        PlatformCrates.LockFileMarker.Should().NotContain("\n");
        PlatformCrates.LockFileMarker.All(c => c >= 0x20 && c < 0x7f).Should().BeTrue();
    }

    [Fact]
    public void AddMarker_puts_the_marker_on_the_third_line_directly_after_cargos_header()
    {
        //Arrange
        var text = Lock(("a", "1.0.0", Registry));

        //Act
        var marked = LockFileRules.AddMarker(text);

        //Assert
        var lines = marked.Split('\n');
        lines[0].Should().Be(LockFileRules.HeaderLine);
        lines[1].Should().Be(LockFileRules.SecondHeaderLine);
        lines[2].Should().Be(PlatformCrates.LockFileMarker);
        lines[3].Should().Be("version = 4");
        marked.Remove(marked.IndexOf(PlatformCrates.LockFileMarker, StringComparison.Ordinal), PlatformCrates.LockFileMarker.Length + 1).Should().Be(text);
    }

    [Fact]
    public void AddMarker_leaves_a_marked_text_as_it_is()
    {
        //Arrange
        var marked = LockFileRules.AddMarker(Lock());

        //Act
        var again = LockFileRules.AddMarker(marked);

        //Assert
        again.Should().Be(marked);
    }

    [Fact]
    public void AddMarker_keeps_windows_line_endings()
    {
        //Arrange
        var text = Lock(("a", "1.0.0", Registry)).Replace("\n", "\r\n");

        //Act
        var marked = LockFileRules.AddMarker(text);

        //Assert
        marked.Split("\r\n")[2].Should().Be(PlatformCrates.LockFileMarker);
    }

    [Fact]
    public void AddMarker_refuses_a_text_without_cargos_header()
    {
        //Act
        Action act = () => LockFileRules.AddMarker("version = 4\n");

        //Assert
        act.Should().Throw<InvalidOperationException>().WithMessage("*header*");
    }

    [Fact]
    public void AddMarker_marks_the_platforms_lock_file_on_its_third_line()
    {
        //Act
        var marked = LockFileRules.AddMarker(PlatformCrates.LockFileText);

        //Assert
        marked.Split('\n')[2].Should().Be(PlatformCrates.LockFileMarker);
        LockFileRules.HasMarker(PlatformCrates.LockFileText).Should().BeFalse();
        LockFileRules.HasMarker(marked).Should().BeTrue();
    }

    [Theory]
    [InlineData(true, "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n# CodeBrix.WebPlatform keeps this file in step with the platform's crates. Remove this line to manage the file yourself.\nversion = 4\n")]
    [InlineData(true, "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n# CodeBrix.WebPlatform keeps this file in step - reworded in a later version.\nversion = 4\n")]
    [InlineData(true, "# This file is automatically @generated by Cargo.\r\n# It is not intended for manual editing.\r\n# CodeBrix.WebPlatform keeps this file in step with the platform's crates.\r\nversion = 4\r\n")]
    [InlineData(false, "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n")]
    [InlineData(false, "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n# CodeBrix.WebPlatform keeps this file in step with the platform's crates.\n")]
    [InlineData(false, "# This file is automatically @generated by Cargo.\n#  CodeBrix.WebPlatform keeps this file in step\nversion = 4\n")]
    public void HasMarker_recognises_the_prefix_among_the_leading_comment_lines_only(bool expected, string text)
        => LockFileRules.HasMarker(text).Should().Be(expected);

    [Fact]
    public void ReadCratesIoPackages_reads_the_crates_io_entries_only()
    {
        //Arrange
        var text = Lock(("app", "0.1.0", null), ("a", "1.0.0", Registry), ("g", "2.0.0", "git+https://example.com/g#abc"), ("b", "2.0.0", Registry));

        //Act
        var packages = LockFileRules.ReadCratesIoPackages(text);

        //Assert
        packages.Select(p => p.ToString()).Should().Equal("a 1.0.0", "b 2.0.0");
    }

    [Fact]
    public void ReadCratesIoPackages_gives_nothing_for_a_text_that_is_not_toml()
        => LockFileRules.ReadCratesIoPackages("[[package]\nname = ").Should().BeEmpty();

    [Fact]
    public void ReadCratesIoPackages_reads_the_platforms_lock_file()
    {
        //Act
        var packages = LockFileRules.ReadCratesIoPackages(PlatformCrates.LockFileText);

        //Assert
        packages.Should().Contain(p => p.Name == "dioxus" && p.Version == "0.7.10");
        packages.Should().NotContain(p => p.Name == "codebrix-webplatform");
    }

    [Fact]
    public void FindStale_finds_a_platform_crate_that_moved()
    {
        //Arrange
        var locked = LockFileRules.ReadCratesIoPackages(Lock(("web-sys", "0.3.1", Registry), ("syn", "2.0.1", Registry)));

        //Act
        var stale = LockFileRules.FindStale(locked, Vendored("web-sys 0.3.2", "syn 2.0.1"));

        //Assert
        stale.Select(s => s.ToString()).Should().Equal("web-sys 0.3.1");
    }

    [Fact]
    public void FindStale_finds_a_bundle_crate_that_moved()
    {
        //Arrange
        var locked = LockFileRules.ReadCratesIoPackages(Lock(("web-sys", "0.3.1", Registry), ("wgpu", "30.0.2", Registry)));

        //Act
        var stale = LockFileRules.FindStale(locked, Vendored("web-sys 0.3.1", "wgpu 31.0.0"));

        //Assert
        stale.Select(s => s.ToString()).Should().Equal("wgpu 30.0.2");
    }

    [Fact]
    public void FindStale_leaves_out_a_crate_the_vendor_folder_never_carried()
    {
        //Arrange
        var locked = LockFileRules.ReadCratesIoPackages(Lock(("own-crate", "1.0.0", Registry)));

        //Act
        var stale = LockFileRules.FindStale(locked, Vendored("web-sys 0.3.1"));

        //Assert
        stale.Should().BeEmpty();
    }

    [Fact]
    public void FindStale_accepts_one_of_two_versions_the_vendor_folder_holds()
    {
        //Arrange
        var locked = LockFileRules.ReadCratesIoPackages(Lock(("syn", "2.0.1", Registry)));

        //Act
        var stale = LockFileRules.FindStale(locked, Vendored("syn 1.0.9", "syn 2.0.1"));

        //Assert
        stale.Should().BeEmpty();
    }

    [Fact]
    public void UpdateArguments_name_each_stale_crate_with_its_version_only_where_the_name_is_ambiguous()
    {
        //Arrange
        var locked = LockFileRules.ReadCratesIoPackages(Lock(("a", "1.0.0", Registry), ("syn", "1.0.0", Registry), ("syn", "2.0.0", Registry)));
        var stale = LockFileRules.FindStale(locked, Vendored("a 1.1.0", "syn 2.0.0", "syn 1.0.9"));

        //Act
        var arguments = LockFileRules.UpdateArguments(stale, locked);

        //Assert
        arguments.Should().Equal("update", "--offline", "-p", "a", "-p", "syn@1.0.0");
        LockFileRules.UpdateCommand(stale, locked).Should().Be("cargo update --offline -p a -p syn@1.0.0");
    }

    [Fact]
    public void DescribeRepairs_pairs_each_stale_entry_with_the_version_cargo_locked_instead()
    {
        //Arrange
        var before = LockFileRules.ReadCratesIoPackages(Lock(("a", "1.0.0", Registry), ("b", "1.0.0", Registry), ("keep", "2.0.0", Registry)));
        var after = LockFileRules.ReadCratesIoPackages(Lock(("a", "1.1.0", Registry), ("keep", "2.0.0", Registry)));
        var stale = LockFileRules.FindStale(before, Vendored("a 1.1.0", "b 1.2.0", "keep 2.0.0"));

        //Act
        var repairs = LockFileRules.DescribeRepairs(stale, before, after);

        //Assert
        repairs.Select(r => r.ToString()).Should().Equal("a 1.0.0 -> 1.1.0", "b 1.0.0 -> removed");
        repairs[0].Crate.Should().Be("a");
        repairs[0].OldVersion.Should().Be("1.0.0");
        repairs[0].NewVersion.Should().Be("1.1.0");
        repairs[1].NewVersion.Should().BeNull();
    }

    [Fact]
    public void StaleMessage_for_a_file_without_the_marker_names_the_entries_the_folder_and_the_exact_command()
    {
        //Arrange
        var locked = LockFileRules.ReadCratesIoPackages(Lock(("a", "1.0.0", Registry), ("b", "2.0.0", Registry)));
        var vendored = Vendored("a 1.1.0", "b 2.1.0");
        var stale = LockFileRules.FindStale(locked, vendored);

        //Act
        var message = LockFileRules.StaleMessage("/app/frontend", stale, locked, vendored, marked: false);

        //Assert
        message.Should().Contain("'/app/frontend'");
        message.Should().Contain("a 1.0.0 (the vendor folder holds 1.1.0), b 2.0.0 (the vendor folder holds 2.1.0)");
        message.Should().Contain("was not changed");
        message.Should().Contain(Environment.NewLine + "    cargo update --offline -p a -p b");
        message.Should().Contain(PlatformCrates.LockFileMarker);
    }

    [Fact]
    public void StaleMessage_for_a_marked_file_says_to_materialize()
    {
        //Arrange
        var locked = LockFileRules.ReadCratesIoPackages(Lock(("a", "1.0.0", Registry)));
        var vendored = Vendored("a 1.1.0");

        //Act
        var message = LockFileRules.StaleMessage("/app/frontend", LockFileRules.FindStale(locked, vendored), locked, vendored, marked: true);

        //Assert
        message.Should().Contain("call MaterializeAsync first");
        message.Should().Contain("cargo update --offline -p a");
    }
}
