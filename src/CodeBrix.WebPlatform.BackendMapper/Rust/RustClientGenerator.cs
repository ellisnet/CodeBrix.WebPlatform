using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using CodeBrix.Templating;
using CodeBrix.Templating.Runtime;
using CodeBrix.WebPlatform.BackendMapper.Model;
using CodeBrix.WebPlatform.BackendMapper.Rust.View;

namespace CodeBrix.WebPlatform.BackendMapper.Rust;

/// <summary>
/// Writes the Rust client code for a mapped backend by applying the templates to the map: the
/// contract classes and enums (<c>models.rs</c>), one function per REST endpoint (<c>api.rs</c>),
/// one type per SignalR hub (<c>hubs.rs</c>) and the module file that declares them (<c>mod.rs</c>).
/// </summary>
public static class RustClientGenerator
{
    /// <summary>The marker line every generated file starts with.</summary>
    public const string GeneratedMarker = "// @generated by CodeBrix.WebPlatform.BackendMapper";

    /// <summary>Produces the client code in memory.</summary>
    /// <param name="map">The mapped backend.</param>
    /// <param name="options">How to write the code; null for the defaults.</param>
    /// <returns>The files, ordered by path. <c>api.rs</c> is left out when the backend has no
    /// endpoints and <c>hubs.rs</c> when it has no hubs.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="map"/> is null.</exception>
    /// <exception cref="BackendMapException">A template has a syntax error or fails while it is applied.</exception>
    public static IReadOnlyList<GeneratedFile> Generate(BackendMap map, RustClientOptions options = null)
    {
        ArgumentNullException.ThrowIfNull(map);
        options ??= new RustClientOptions();
        var templates = options.Templates ?? new RustTemplates();
        var view = new ViewBuilder(options).Build(map);
        var files = new List<GeneratedFile>
        {
            new("mod.rs", Render("mod", templates.Module, view)),
            new("models.rs", Render("models", templates.Models, view)),
        };
        if (view.HasApi)
        {
            files.Add(new GeneratedFile("api.rs", Render("api", templates.Api, view)));
        }

        if (view.HasHubs)
        {
            files.Add(new GeneratedFile("hubs.rs", Render("hubs", templates.Hubs, view)));
        }

        files.Sort((left, right) => string.CompareOrdinal(left.RelativePath, right.RelativePath));
        return files;
    }

    /// <summary>
    /// Makes a folder hold exactly the given generated files. Files that already have the right
    /// content are left untouched (so cargo does not rebuild for nothing), changed and missing
    /// files are written, and other files in the folder that carry the generated marker are deleted.
    /// </summary>
    /// <param name="directory">The folder, such as the frontend's <c>src/generated</c>. It is
    /// created when missing. The folder belongs to the generated code.</param>
    /// <param name="files">The files from <see cref="Generate(BackendMap, RustClientOptions)"/>.</param>
    /// <returns>The paths, relative to <paramref name="directory"/>, of the files written or deleted.</returns>
    /// <exception cref="ArgumentException"><paramref name="directory"/> is null or blank.</exception>
    /// <exception cref="ArgumentNullException"><paramref name="files"/> is null.</exception>
    /// <exception cref="InvalidOperationException">The folder holds a file that was not generated,
    /// so writing into it could destroy hand-written code.</exception>
    public static IReadOnlyList<string> WriteTo(string directory, IEnumerable<GeneratedFile> files)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(directory);
        ArgumentNullException.ThrowIfNull(files);
        var root = Path.GetFullPath(directory);
        var wanted = files.ToDictionary(f => f.RelativePath, f => f.Content, StringComparer.Ordinal);
        var encoding = new UTF8Encoding(false);
        var stale = new List<string>();
        if (Directory.Exists(root))
        {
            foreach (var existing in Directory.EnumerateFiles(root, "*", SearchOption.AllDirectories))
            {
                var relative = Path.GetRelativePath(root, existing).Replace(Path.DirectorySeparatorChar, '/');
                if (wanted.ContainsKey(relative))
                {
                    continue;
                }

                using var reader = new StreamReader(existing);
                var firstLine = reader.ReadLine() ?? string.Empty;
                if (!firstLine.StartsWith(GeneratedMarker, StringComparison.Ordinal))
                {
                    throw new InvalidOperationException(
                        $"The folder '{root}' holds '{relative}', which was not generated. Nothing was written. Choose a folder that is used for generated code only.");
                }

                stale.Add(relative);
            }
        }

        Directory.CreateDirectory(root);
        var changed = new List<string>();
        foreach (var (relative, content) in wanted)
        {
            var target = Path.Combine(root, relative.Replace('/', Path.DirectorySeparatorChar));
            if (File.Exists(target) && File.ReadAllText(target, encoding) == content)
            {
                continue;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(target));
            File.WriteAllText(target, content, encoding);
            changed.Add(relative);
        }

        foreach (var relative in stale)
        {
            File.Delete(Path.Combine(root, relative.Replace('/', Path.DirectorySeparatorChar)));
            changed.Add(relative);
        }

        changed.Sort(StringComparer.Ordinal);
        return changed;
    }

    private static string Render(string name, string templateText, ClientView view)
    {
        if (string.IsNullOrWhiteSpace(templateText))
        {
            throw new BackendMapException($"The '{name}' template is empty.");
        }

        var template = Template.Parse(templateText.Replace("\r\n", "\n", StringComparison.Ordinal), name + ".sbn");
        if (template.HasErrors)
        {
            throw new BackendMapException($"The '{name}' template has errors:{Environment.NewLine}{string.Join(Environment.NewLine, template.Messages.Select(m => "  " + m))}");
        }

        var globals = new ScriptObject();
        globals.Import(view);
        var context = new TemplateContext { LoopLimit = 0, NewLine = "\n", StrictVariables = true };
        context.PushGlobal(globals);
        string text;
        try
        {
            text = template.Render(context);
        }
        catch (Exception e) when (e is not OutOfMemoryException)
        {
            throw new BackendMapException($"The '{name}' template failed while it was applied: {e.Message}", e);
        }

        //One trailing newline, no trailing spaces, no runs of blank lines.
        var lines = text.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n').Select(l => l.TrimEnd()).ToList();
        var result = new StringBuilder();
        var blank = 0;
        foreach (var line in lines)
        {
            blank = line.Length == 0 ? blank + 1 : 0;
            if (blank <= 1)
            {
                result.Append(line).Append('\n');
            }
        }

        return result.ToString().TrimEnd('\n') + "\n";
    }
}
