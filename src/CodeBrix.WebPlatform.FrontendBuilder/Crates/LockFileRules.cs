using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using CodeBrix.RustTools;
using CodeBrix.RustTools.Projects;

namespace CodeBrix.WebPlatform.FrontendBuilder.Crates;

/// <summary>
/// A frontend's <c>Cargo.lock</c> as <see cref="PlatformFrontend.MaterializeAsync"/> sees it: the
/// platform's marker line (<see cref="PlatformCrates.LockFileMarker"/>), and the entries that name
/// a version of a crate the vendor folder holds only in other versions ("stale" entries), with
/// the cargo command that brings exactly those entries in step.
/// </summary>
internal static class LockFileRules
{
    /// <summary>The lock file's name in the frontend folder.</summary>
    internal const string FileName = "Cargo.lock";

    /// <summary>The first line cargo writes into every lock file.</summary>
    internal const string HeaderLine = "# This file is automatically @generated by Cargo.";

    /// <summary>The second line cargo writes into every lock file.</summary>
    internal const string SecondHeaderLine = "# It is not intended for manual editing.";

    /// <summary>
    /// The source of crates.io's crates in a lock file: the one source the cargo configuration of
    /// <see cref="CrateMode.PlatformCratesOnly"/> replaces with the vendor folder.
    /// </summary>
    internal const string CratesIoSource = "registry+https://github.com/rust-lang/crates.io-index";

    /// <summary>
    /// True when the lock file's leading comment lines (the ones cargo keeps when it rewrites the
    /// file) include a line that starts with <see cref="PlatformCrates.LockFileMarkerPrefix"/>.
    /// </summary>
    /// <param name="text">The lock file's text.</param>
    internal static bool HasMarker(string text)
        => LeadingComments(text).Any(l => l.StartsWith(PlatformCrates.LockFileMarkerPrefix, StringComparison.Ordinal));

    /// <summary>
    /// The lock text with <see cref="PlatformCrates.LockFileMarker"/> as its third line, directly
    /// after cargo's two header lines (the only place cargo keeps a comment both on an ordinary
    /// build and when it rewrites the file). A text that already has the marker is returned as
    /// it is.
    /// </summary>
    /// <param name="text">A lock file cargo wrote.</param>
    /// <returns>The text with the marker.</returns>
    /// <exception cref="InvalidOperationException">The text does not start with cargo's two header lines.</exception>
    internal static string AddMarker(string text)
    {
        if (HasMarker(text))
        {
            return text;
        }

        if (!HasCargoHeader(text))
        {
            throw new InvalidOperationException("The lock file does not start with cargo's two header lines, so the marker line has no place to go.");
        }

        var newLine = NewLine(text);
        var header = HeaderLine + newLine + SecondHeaderLine + newLine;
        return header + PlatformCrates.LockFileMarker + newLine + text.Substring(header.Length);
    }

    /// <summary>True when the text starts with cargo's two header lines (the place for the marker).</summary>
    /// <param name="text">The lock file's text.</param>
    internal static bool HasCargoHeader(string text)
    {
        var newLine = NewLine(text);
        return text.StartsWith(HeaderLine + newLine + SecondHeaderLine + newLine, StringComparison.Ordinal);
    }

    private static string NewLine(string text) => text.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";

    /// <summary>
    /// The entries of the lock file whose source is crates.io (the ones a vendor folder replaces),
    /// in file order, read with CodeBrix.RustTools' lock-file parser. A text that is not valid
    /// TOML gives none: cargo then reports the file itself.
    /// </summary>
    /// <param name="text">The lock file's text.</param>
    internal static IReadOnlyList<LockedCrate> ReadCratesIoPackages(string text)
    {
        try
        {
            return CargoLockFile.Parse(text, null).Packages
                .Where(p => p.Name != null && p.Version != null && string.Equals(p.Source, CratesIoSource, StringComparison.Ordinal))
                .Select(p => new LockedCrate(p.Name, p.Version))
                .ToList();
        }
        catch (RustToolsException)
        {
            return Array.Empty<LockedCrate>();
        }
    }

    /// <summary>
    /// The locked crates.io entries that name a version of a crate which the vendor folder holds,
    /// but only in other versions. A crate the vendor folder does not carry at all is not stale
    /// (cargo reports it; that is a matter of the crate mode), and neither is a locked version
    /// the folder holds beside others.
    /// </summary>
    /// <param name="locked">The lock file's crates.io entries.</param>
    /// <param name="vendored">The vendor folder's crates: name to versions.</param>
    internal static IReadOnlyList<LockedCrate> FindStale(IReadOnlyList<LockedCrate> locked, IReadOnlyDictionary<string, HashSet<string>> vendored)
        => locked.Where(c => vendored.TryGetValue(c.Name, out var versions) && !versions.Contains(c.Version)).ToList();

    /// <summary>
    /// The arguments of <c>cargo update</c> that bring exactly the stale entries in step:
    /// <c>update --offline -p a -p b</c>, with <c>name@version</c> where the lock file names more
    /// than one version of the crate (cargo refuses a bare name that is ambiguous).
    /// </summary>
    /// <param name="stale">The stale entries.</param>
    /// <param name="locked">All the lock file's crates.io entries.</param>
    internal static IReadOnlyList<string> UpdateArguments(IReadOnlyList<LockedCrate> stale, IReadOnlyList<LockedCrate> locked)
    {
        var arguments = new List<string> { "update", "--offline" };
        foreach (var crate in stale)
        {
            arguments.Add("-p");
            arguments.Add(locked.Count(c => c.Name == crate.Name) > 1 ? crate.Name + "@" + crate.Version : crate.Name);
        }

        return arguments;
    }

    /// <summary>The command a developer runs in the frontend folder: <c>cargo update --offline -p a -p b</c>.</summary>
    /// <param name="stale">The stale entries.</param>
    /// <param name="locked">All the lock file's crates.io entries.</param>
    internal static string UpdateCommand(IReadOnlyList<LockedCrate> stale, IReadOnlyList<LockedCrate> locked)
        => "cargo " + string.Join(" ", UpdateArguments(stale, locked));

    /// <summary>
    /// What each stale entry became after <c>cargo update</c>: the versions of the crate the new
    /// lock file names that the old one did not, paired with the stale versions in order
    /// (<c>null</c> when cargo dropped the crate).
    /// </summary>
    /// <param name="stale">The stale entries of the old lock file.</param>
    /// <param name="before">The old lock file's crates.io entries.</param>
    /// <param name="after">The new lock file's crates.io entries.</param>
    internal static IReadOnlyList<LockFileRepair> DescribeRepairs(IReadOnlyList<LockedCrate> stale, IReadOnlyList<LockedCrate> before, IReadOnlyList<LockedCrate> after)
    {
        var repairs = new List<LockFileRepair>();
        foreach (var group in stale.GroupBy(c => c.Name, StringComparer.Ordinal))
        {
            var old = before.Where(c => c.Name == group.Key).Select(c => c.Version).ToHashSet(StringComparer.Ordinal);
            var added = after.Where(c => c.Name == group.Key && !old.Contains(c.Version)).Select(c => c.Version).OrderBy(v => v, StringComparer.Ordinal).ToList();
            var index = 0;
            foreach (var crate in group.OrderBy(c => c.Version, StringComparer.Ordinal))
            {
                repairs.Add(new LockFileRepair(crate.Name, crate.Version, index < added.Count ? added[index] : null));
                index++;
            }
        }

        return repairs;
    }

    /// <summary>
    /// The stale entries as text for a message: "name version (the vendor folder holds x, y)".
    /// </summary>
    /// <param name="stale">The stale entries.</param>
    /// <param name="vendored">The vendor folder's crates.</param>
    internal static string Describe(IReadOnlyList<LockedCrate> stale, IReadOnlyDictionary<string, HashSet<string>> vendored)
        => string.Join(", ", stale.Select(c => $"{c.Name} {c.Version} (the vendor folder holds {string.Join(", ", vendored[c.Name].OrderBy(v => v, StringComparer.Ordinal))})"));

    /// <summary>
    /// The message for a lock file with stale entries that MaterializeAsync does not change: one
    /// without the marker (the developer's own), or - before a build - one with the marker in a
    /// frontend that has not been materialized since the crates changed.
    /// </summary>
    /// <param name="frontend">The frontend folder.</param>
    /// <param name="stale">The stale entries.</param>
    /// <param name="locked">All the lock file's crates.io entries.</param>
    /// <param name="vendored">The vendor folder's crates.</param>
    /// <param name="marked">Whether the lock file carries the marker.</param>
    internal static string StaleMessage(string frontend, IReadOnlyList<LockedCrate> stale, IReadOnlyList<LockedCrate> locked, IReadOnlyDictionary<string, HashSet<string>> vendored, bool marked)
    {
        var text = new StringBuilder();
        text.Append($"The {FileName} of the frontend '{frontend}' names versions of crates that the platform's crates and the registered crate bundles no longer hold: ");
        text.Append(Describe(stale, vendored)).Append(". The offline build fails until the file is brought in step. ");
        if (marked)
        {
            text.Append("The file carries the CodeBrix.WebPlatform marker line: call MaterializeAsync first, which brings it in step, or run this command in that folder:");
        }
        else
        {
            text.Append("The file has no CodeBrix.WebPlatform marker line, so it is the application's own and was not changed. Run this command in that folder and commit the changed file:");
        }

        text.Append(Environment.NewLine).Append("    ").Append(UpdateCommand(stale, locked));
        if (!marked)
        {
            text.Append(Environment.NewLine).Append("To let MaterializeAsync do this from now on, put this line back as the file's third line: ").Append(PlatformCrates.LockFileMarker);
        }

        return text.ToString();
    }

    private static IEnumerable<string> LeadingComments(string text)
        => text.Split('\n').Select(l => l.TrimEnd('\r')).TakeWhile(l => l.StartsWith('#'));

    /// <summary>One crates.io entry of a lock file: a crate's name and version.</summary>
    internal sealed record LockedCrate(string Name, string Version)
    {
        /// <summary>"name version".</summary>
        /// <returns>The text.</returns>
        public override string ToString() => Name + " " + Version;
    }
}
